        print(f" TRAINING COMPLETE!")
        print(f" Best Reward: {self.best_reward:,.0f} PKR")
        print(f" Best Accuracy: {self.best_accuracy:.1f}%")
        print(f" Final Accuracy: {self.accuracies[-1]:.1f}%")
        print("="*50)

