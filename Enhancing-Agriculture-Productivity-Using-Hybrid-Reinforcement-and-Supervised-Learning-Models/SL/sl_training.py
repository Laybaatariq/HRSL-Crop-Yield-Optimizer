def convert_to_full_months(text):
    if pd.isnull(text):
        return text
    matches = re.findall(r'\b(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b', text)
    full_months = [month_map[m] for m in matches if m in month_map]
